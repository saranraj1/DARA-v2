class TestBlastRadiusAnalyzer:

    @pytest.mark.asyncio
    async def test_low_risk_single_downstream(self):
        """1 downstream service, no API contract → risk=low."""
        mock_neo4j = AsyncMock()
        mock_neo4j.get_downstream_services.return_value = [
            {"service": "billing-svc", "hop_count": 1, "call_count": 100}
        ]
        mock_neo4j.get_callers.return_value = []

        analyzer = BlastRadiusAnalyzer(neo4j=mock_neo4j)
        fix = make_fix([make_patch("app/utils.py", "+def helper(): pass\n")])
        report = await analyzer.analyze(fix, "payment-svc")

        assert report.risk_level == "low"
        assert report.downstream_count == 1
        assert not report.has_contract_change

    @pytest.mark.asyncio
    async def test_medium_risk_multiple_downstream(self):
        """2 downstream services, no API contract → risk=medium."""
        mock_neo4j = AsyncMock()
        mock_neo4j.get_downstream_services.return_value = [
            {"service": "billing-svc", "hop_count": 1, "call_count": 100},
            {"service": "audit-svc", "hop_count": 2, "call_count": 50},
        ]
        mock_neo4j.get_callers.return_value = []

        analyzer = BlastRadiusAnalyzer(neo4j=mock_neo4j)
        fix = make_fix()
        report = await analyzer.analyze(fix, "payment-svc")

        assert report.risk_level == "medium"

    @pytest.mark.asyncio
    async def test_high_risk_api_contract_modified(self):
        """API contract file modified → risk=high."""
        mock_neo4j = AsyncMock()
        mock_neo4j.get_downstream_services.return_value = [
            {"service": "billing-svc", "hop_count": 1, "call_count": 100}
        ]
        mock_neo4j.get_callers.return_value = []

        # Diff that adds a FastAPI route
        route_diff = '+@router.get("/payments/{id}")\n+async def get_payment(id: str): ...\n'
        fix = make_fix([make_patch("api/routes/payments.py", route_diff)])

        analyzer = BlastRadiusAnalyzer(neo4j=mock_neo4j)
        report = await analyzer.analyze(fix, "payment-svc")

        assert report.has_contract_change
        assert report.risk_level in ("high", "critical")

    @pytest.mark.asyncio
    async def test_critical_risk_api_contract_many_downstream(self):
        """API contract + >3 downstream → risk=critical."""
        mock_neo4j = AsyncMock()
        mock_neo4j.get_downstream_services.return_value = [
            {"service": f"svc-{i}", "hop_count": 1, "call_count": 10}
            for i in range(4)   # 4 downstream services
        ]
        mock_neo4j.get_callers.return_value = []

        route_diff = '+@app.post("/orders")\n+async def create_order(): ...\n'
        fix = make_fix([make_patch("api/routes/orders.py", route_diff)])

        analyzer = BlastRadiusAnalyzer(neo4j=mock_neo4j)
        report = await analyzer.analyze(fix, "order-svc")

        assert report.risk_level == "critical"
        assert report.downstream_count == 4

    @pytest.mark.asyncio
    async def test_api_contract_detected_by_path(self):
        """File in routes/ directory is auto-detected as API contract."""
        mock_neo4j = AsyncMock()
        mock_neo4j.get_downstream_services.return_value = []
        mock_neo4j.get_callers.return_value = []

        fix = make_fix([make_patch("api/routes/orders.py", "+x = 1\n")])
        analyzer = BlastRadiusAnalyzer(neo4j=mock_neo4j)
        report = await analyzer.analyze(fix, "order-svc")

        assert "api/routes/orders.py" in report.shared_api_contracts

    @pytest.mark.asyncio
    async def test_consumer_tests_triggered_when_contract_modified(self):
        """When API contract modified + downstream services exist, TestRunner is called."""
        mock_neo4j = AsyncMock()
        mock_neo4j.get_downstream_services.return_value = [
            {"service": "billing-svc", "hop_count": 1, "call_count": 100}
        ]
        mock_neo4j.get_callers.return_value = []

        route_diff = '+@router.post("/charge")\n+async def charge(): ...\n'
        fix = make_fix([make_patch("api/routes/charge.py", route_diff)])

