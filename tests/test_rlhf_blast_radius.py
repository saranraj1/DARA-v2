class TestGitHubWebhookEndpoint:

    def _make_client(self):
        from fastapi import FastAPI
        from api.routes.webhook_github import router
        app = FastAPI()
        app.include_router(router)
        return TestClient(app, raise_server_exceptions=False)

    def _sign_body(self, body: bytes, secret: str) -> str:
        return "sha256=" + hmac.new(secret.encode(), body, hashlib.sha256).hexdigest()

    def test_invalid_signature_returns_403(self):
        client = self._make_client()
        body = json.dumps({"action": "closed"}).encode()
        with patch("api.routes.webhook_github.get_settings") as mock_settings:
            mock_settings.return_value.github_webhook_secret = "real-secret"
            response = client.post(
                "/webhooks/github/pr-feedback",
                content=body,
                headers={
                    "X-GitHub-Event": "pull_request",
                    "X-Hub-Signature-256": "sha256=bad_signature",
                    "Content-Type": "application/json",
                },
            )
        assert response.status_code == 403

    def test_valid_signature_returns_202(self):
        client = self._make_client()
        payload = {
            "action": "closed",
            "pull_request": {
                "number": 1,
                "body": SAMPLE_PR_BODY,
                "merged": True,
            },
        }
        body = json.dumps(payload).encode()
        secret = "test-webhook-secret"
        sig = self._sign_body(body, secret)

        mock_processor = MagicMock()
        mock_processor.on_pr_merged = AsyncMock(return_value=MagicMock())

        with (
            patch("api.routes.webhook_github.get_settings") as mock_settings,
            patch("api.routes.webhook_github._get_processor", return_value=mock_processor),
        ):
            mock_settings.return_value.github_webhook_secret = secret
            response = client.post(
                "/webhooks/github/pr-feedback",
                content=body,
                headers={
                    "X-GitHub-Event": "pull_request",
                    "X-Hub-Signature-256": sig,
                    "Content-Type": "application/json",
                },
            )
        # FastAPI TestClient may return 200 or 202 depending on how BackgroundTasks run
        assert response.status_code in (200, 202)
        assert response.json()["status"] == "accepted"

    def test_ping_event_returns_200_pong(self):
        client = self._make_client()
        body = json.dumps({"zen": "Keep it logically awesome."}).encode()
        with patch("api.routes.webhook_github.get_settings") as mock_settings:
            mock_settings.return_value.github_webhook_secret = ""
            response = client.post(
                "/webhooks/github/pr-feedback",
                content=body,
                headers={
                    "X-GitHub-Event": "ping",
                    "Content-Type": "application/json",
                },
            )
        assert response.status_code == 200
        assert response.json()["status"] == "pong"


