class TestPolyglotASTChunker:

    def test_python_file_produces_function_chunks(self):
        chunker = ASTChunker()
        source = """\
def greet(name: str) -> str:
    msg = f"Hello, {name}!"
    return msg

class UserHandler:
    def handle(self, request):
        result = self.process(request)
        return result

    def process(self, request):
        validated = self._validate(request)
        return validated
"""
        chunks = chunker.chunk_file("app.py", source=source)
        fn_names = [c.function_name for c in chunks if c.function_name]
        assert "greet" in fn_names

    def test_go_file_fallback_on_missing_lib(self):
        """Go chunker gracefully falls back to line-window when tree-sitter-go missing."""
        chunker = ASTChunker()
        # Force go parser to None
        chunker._parsers["go"] = None

        source = """\
package main

import "fmt"

func Greet(name string) string {
    return fmt.Sprintf("Hello, %s!", name)
}

func main() {
    fmt.Println(Greet("world"))
}
"""
        chunks = chunker.chunk_file("main.go", source=source)
        # Fallback produces at least one chunk
        assert len(chunks) >= 1
        assert all(c.language == "go" for c in chunks)

    def test_typescript_file_fallback_on_missing_lib(self):
        """TS chunker gracefully falls back when tree-sitter-typescript missing."""
        chunker = ASTChunker()
        chunker._parsers["typescript"] = None

        source = """\
export async function fetchUser(id: string): Promise<User> {
    const response = await fetch(`/api/users/${id}`);
    return response.json();
}

const processOrder = async (order: Order) => {
    return await db.save(order);
};
"""
        chunks = chunker.chunk_file("user.ts", source=source)
        assert len(chunks) >= 1
        assert all(c.language == "typescript" for c in chunks)

    def test_go_ast_chunks_functions_when_parser_available(self):
        """If tree-sitter-go is installed, produce function-level Go chunks."""
        chunker = ASTChunker()
        if chunker._parsers.get("go") is None:
            pytest.skip("tree-sitter-go not installed")

        source = """\
package payments

import "errors"

func Charge(amount float64) error {
    if amount <= 0 {
        return errors.New("invalid amount")
    }
    return nil
}

func Refund(txID string) error {
    return nil
}
"""
        chunks = chunker.chunk_file("payments.go", source=source)
        fn_names = [c.function_name for c in chunks if c.function_name]
        assert "Charge" in fn_names or len(chunks) >= 1  # fallback also acceptable

    def test_typescript_ast_chunks_functions_when_parser_available(self):
        """If tree-sitter-typescript is installed, produce function-level TS chunks."""
        chunker = ASTChunker()
        if chunker._parsers.get("typescript") is None:
            pytest.skip("tree-sitter-typescript not installed")

        source = """\
export async function createOrder(data: OrderData): Promise<Order> {
    const order = new Order(data);
    await order.save();
    return order;
}

export class OrderService {
    async cancel(id: string): Promise<void> {
        await Order.delete(id);
    }
}
"""
        chunks = chunker.chunk_file("orders.ts", source=source)
        fn_names = [c.function_name for c in chunks if c.function_name]
        assert "createOrder" in fn_names or len(chunks) >= 1

    def test_unknown_language_uses_fallback(self):
        """File with unknown extension uses sliding-window fallback."""
        chunker = ASTChunker()
        source = "\n".join(f"line {i}" for i in range(100))
        chunks = chunker.chunk_file("script.rb", source=source)
        assert len(chunks) >= 1
        assert all(c.language == "ruby" for c in chunks)
