def make_patch(file_path: str = "app/main.py", diff: str = "+x = 1\n") -> PatchFile:
    return PatchFile(
        file_path=file_path, unified_diff=diff,
        lines_changed=1, change_description="test",
    )


def make_fix(patches=None) -> Fix:
    patches = patches or [make_patch()]
    return Fix(
        error_id="err-001", patches=patches,
        total_files_changed=len(patches), total_lines_changed=1,
        fix_explanation="test fix", suggested_tests=[],
        confidence_retained=0.8, regression_risk="low",
        strategy="llm_single_file", llm_provider="groq",
    )


def _make_processor(qdrant=None, neo4j=None, postgres=None, memory=None):
    return PRFeedbackProcessor(
        qdrant=qdrant or AsyncMock(),
        neo4j=neo4j or AsyncMock(),
        postgres=postgres or AsyncMock(),
        memory=memory or AsyncMock(),
    )


